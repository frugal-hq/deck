const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('deck', {
  pickFolder: () => ipcRenderer.invoke('folder:pick'),
  pickFiles: () => ipcRenderer.invoke('files:pick'),
  pathForFile: (file) => webUtils.getPathForFile(file),
  thumbnail: (file) => ipcRenderer.invoke('files:thumbnail', file),
  savePasted: (bytes, type) => ipcRenderer.invoke('files:save-pasted', bytes, type),
  defaultFolder: () => ipcRenderer.invoke('folder:default'),
  estimateTopics: (options) => ipcRenderer.invoke('topics:estimate', options),
  runTopics: (options) => ipcRenderer.invoke('topics:run', options),
  restoreTitles: () => ipcRenderer.send('topics:restore-titles'),
  onTopicsProgress: (callback) => ipcRenderer.on('topics:progress', (_, done, total) => callback(done, total)),
  start: (options) => ipcRenderer.invoke('chat:start', options),
  input: (id, data) => ipcRenderer.send('chat:input', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('chat:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('chat:kill', id),
  onData: (callback) => ipcRenderer.on('chat:data', (_, id, data) => callback(id, data)),
  onEdit: (callback) => ipcRenderer.on('chat:edit', (_, id, text) => callback(id, text)),
  saveEdit: (id, text) => ipcRenderer.send('chat:save-edit', id, text),
  onExit: (callback) => ipcRenderer.on('chat:exit', (_, id, code) => callback(id, code)),
  onMeters: (callback) => ipcRenderer.on('chat:meters', (_, id, meters) => callback(id, meters)),
  onRestarting: (callback) => ipcRenderer.on('chat:restarting', (_, id) => callback(id)),
  onTurnEnd: (callback) => ipcRenderer.on('chat:turn-end', (_, id) => callback(id)),
  onHandoff: (callback) => ipcRenderer.on('chat:handoff', (_, id, handoff) => callback(id, handoff)),
  continueIn: (options) => ipcRenderer.invoke('chat:continue', options),
  switchAccount: (options) => ipcRenderer.invoke('chat:switch-account', options),
  setVoiceMode: (mode) => ipcRenderer.send('voice:mode', mode),
  voiceStatus: (model) => ipcRenderer.invoke('voice:status', model),
  voicePrepare: (model) => ipcRenderer.invoke('voice:prepare', model),
  voiceTranscribe: (options) => ipcRenderer.invoke('voice:transcribe', options),
  onVoiceProgress: (callback) => ipcRenderer.on('voice:progress', (_, received, total) => callback(received, total)),
  setAttention: (count) => ipcRenderer.send('window:attention', count),
  login: (options) => ipcRenderer.invoke('accounts:login', options),
  logout: (id) => ipcRenderer.invoke('accounts:logout', { id }),
  removeAccount: (id) => ipcRenderer.invoke('accounts:remove', { id }),
  setPrimary: (id) => ipcRenderer.invoke('accounts:set-primary', { id }),
  getAccounts: () => ipcRenderer.invoke('accounts:get'),
  getRoles: () => ipcRenderer.invoke('settings:roles'),
  setRoles: (on) => ipcRenderer.send('settings:set-roles', on),
  renameAccount: (id, name) => ipcRenderer.invoke('accounts:rename', { id, name }),
  setAccountCap: (id, field, value) => ipcRenderer.invoke('accounts:set-cap', { id, field, value }),
  refreshAccounts: () => ipcRenderer.invoke('accounts:refresh'),
  onAccounts: (callback) => ipcRenderer.on('accounts:changed', (_, state) => callback(state)),
  getSessions: () => ipcRenderer.invoke('sessions:get'),
  getAllSessions: () => ipcRenderer.invoke('sessions:all'),
  organize: (id, organization) => ipcRenderer.send('sessions:organize', id, organization),
  setGroup: (id, name) => ipcRenderer.send('sessions:set-group', id, name),
  setWorkspace: (group, workspace) => ipcRenderer.send('sessions:set-workspace', group, workspace),
  setWorkspaceParent: (name, parent) => ipcRenderer.send('workspaces:set-parent', name, parent),
  renameWorkspace: (from, to) => ipcRenderer.send('workspaces:rename', from, to),
  deleteWorkspace: (name) => ipcRenderer.send('workspaces:delete', name),
  renameGroup: (ids, from, to) => ipcRenderer.send('groups:rename', ids, from, to),
  deleteGroup: (ids, group) => ipcRenderer.send('groups:delete', ids, group),
  clearWorkspaces: () => ipcRenderer.send('workspaces:clear'),
  estimateWorkspaces: () => ipcRenderer.invoke('workspaces:estimate'),
  runWorkspaces: (options) => ipcRenderer.invoke('workspaces:run', options),
  link: (id, parentId) => ipcRenderer.send('sessions:link', id, parentId),
  undoLink: () => ipcRenderer.send('sessions:undo-link'),
  estimateJoins: () => ipcRenderer.invoke('joins:estimate'),
  runJoins: (options) => ipcRenderer.invoke('joins:run', options),
  clearJoins: () => ipcRenderer.send('joins:clear'),
  onSessions: (callback) => ipcRenderer.on('sessions:changed', (_, index) => callback(index)),
  openLink: (url, cwd) => ipcRenderer.send('link:open', url, cwd),
  windowAction: (action) => ipcRenderer.send('window:action', action),
  onMaximized: (callback) => ipcRenderer.on('window:maximized', (_, maximized) => callback(maximized)),
});
